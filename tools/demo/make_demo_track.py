#!/usr/bin/env python3
"""Cut demo mode's track out of the ESP-NOW testlab recording.

Writes DemoTrack.h and DemoTrack.cpp in the sketch root: one row per second, heading and attitude
taken from every second row of the testlab's 2 Hz table. Oil pressure is the testlab's synthetic
curve (it was not recorded), so demo mode shows the same values as the testlab. Depth gaps in the recording are bridged in a straight line, so that no
page drops to its placeholder in demo mode.

Run: python3 tools/demo/make_demo_track.py [path/to/ESPNOW-testlab-gateway]
"""

import argparse
import pathlib
import re

START_UTC = 1792466100   # SimData::START_UTC, the recording's first row
TRACK_START_UTC = 1792473300   # 2026-10-20 05:15:00 UTC = 08:15:00 EEST
TRACK_ROWS = 600

SLOW_FIELDS = ("lat_e7 lon_e7 sog_mms cog_e4 magvar_e4 sats reserved house_v_mv house_i_ca house_p_dw "
               "soc_e2 start_v_mv temp_c_e2 hum_e2 press_pa_o exhaust_k_e2 fuel_e4 water_e4 oil_kpa_e1 "
               "depth_surf_cm depth_tdcr_cm depth_keel_cm depth_age_ds").split()
FAST_FIELDS = "hdg_mag_e4 hdg_true_e4 pitch_e4 roll_e4".split()

ROW_FIELDS = ("lat_e7 lon_e7 sog_mms cog_e4 hdg_true_e4 pitch_e4 roll_e4 depth_surf_cm house_v_mv house_i_ca "
              "soc_e2 start_v_mv temp_c_e2 hum_e2 press_pa_o exhaust_k_e2 fuel_e4 water_e4 oil_kpa_e1").split()

U16_MISSING = 0xFFFF
I16_MISSING = -32768

HEADER = """#pragma once

#include <stdint.h>

// GENERATED by tools/demo/make_demo_track.py - do not edit by hand.
//
// === D E M O  T R A C K ===
//
// - Demo mode's data: 10 min of M/V Frida's recorded instruments,
//   one row per second. Cut from the ESP-NOW testlab's table, whose clock runs 2 h behind the
//   recording: the rows were recorded 2026-10-20 at 10:15 EEST and play as 08:15 EEST.
// - Depth gaps in the recording are bridged in a straight line. Oil pressure was not recorded:
//   it is the testlab's synthetic curve.

namespace DemoTrack {

    static constexpr uint32_t ROWS          = %(rows)dUL;
    static constexpr int64_t  START_UTC     = %(start_utc)dLL;
    static constexpr int32_t  PRESS_OFFSET  = 90000;   // press_pa_o + offset = Pa

    struct Row {
        int32_t  lat_e7;          // degrees x 1e7
        int32_t  lon_e7;          // degrees x 1e7
        uint16_t sog_mms;         // m/s x 1000
        uint16_t cog_e4;          // rad x 1e4, true
        uint16_t hdg_true_e4;     // rad x 1e4
        int16_t  pitch_e4;        // rad x 1e4
        int16_t  roll_e4;         // rad x 1e4
        uint16_t depth_surf_cm;   // m x 100
        uint16_t house_v_mv;      // V x 1000
        int16_t  house_i_ca;      // A x 100
        uint16_t soc_e2;          // percent x 100
        uint16_t start_v_mv;      // V x 1000
        int16_t  temp_c_e2;       // degC x 100
        uint16_t hum_e2;          // percent x 100
        uint16_t press_pa_o;      // Pa - PRESS_OFFSET
        uint16_t exhaust_k_e2;    // K x 100
        uint16_t fuel_e4;         // ratio x 1e4
        uint16_t water_e4;        // ratio x 1e4
        uint16_t oil_kpa_e1;      // kPa x 10, synthetic in the testlab
    };

    extern const Row TRACK[ROWS];

} // namespace DemoTrack
"""


def read_table(text, fields):
    rows = re.findall(r"^\{([-0-9,]+)\},?$", text, re.M)
    return [dict(zip(fields, map(int, row.split(",")))) for row in rows]


def bridge_depth(rows):
    """Straight line over each run of missing depth. The run may not touch either end."""
    known = [i for i, r in enumerate(rows) if r["depth_surf_cm"] != U16_MISSING]
    if not known or known[0] != 0 or known[-1] != len(rows) - 1:
        raise SystemExit("the stretch must start and end with a known depth")
    for a, b in zip(known, known[1:]):
        for i in range(a + 1, b):
            frac = (i - a) / (b - a)
            rows[i]["depth_surf_cm"] = round(rows[a]["depth_surf_cm"] +
                                             (rows[b]["depth_surf_cm"] - rows[a]["depth_surf_cm"]) * frac)
    return len(rows) - len(known)


def main():
    default_lab = pathlib.Path.home() / "Documents/Arduino/ESPNOW-testlab-gateway"
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("testlab", nargs="?", type=pathlib.Path, default=default_lab)
    args = parser.parse_args()

    slow_text, fast_text = (args.testlab / "SimData.cpp").read_text().split("const FastRow FAST")
    slow = read_table(slow_text, SLOW_FIELDS)
    fast = read_table(fast_text, FAST_FIELDS)

    first = TRACK_START_UTC - START_UTC
    rows = []
    for i in range(first, first + TRACK_ROWS):
        rows.append({**slow[i], **fast[i * 2]})
    bridged = bridge_depth(rows)

    for i, row in enumerate(rows):
        for name in ROW_FIELDS:
            if row[name] in (U16_MISSING, I16_MISSING):
                raise SystemExit(f"row {i}: {name} is missing in the recording")

    root = pathlib.Path(__file__).resolve().parents[2]
    (root / "DemoTrack.h").write_text(HEADER % {"rows": TRACK_ROWS, "start_utc": TRACK_START_UTC})
    with open(root / "DemoTrack.cpp", "w") as out:
        out.write("// GENERATED by tools/demo/make_demo_track.py - do not edit by hand.\n")
        out.write('#include "DemoTrack.h"\n\n')
        out.write("namespace DemoTrack {\n\n")
        out.write("// " + ",".join(ROW_FIELDS) + "\n")
        out.write("const Row TRACK[ROWS] = {\n")
        for row in rows:
            out.write("{" + ",".join(str(row[name]) for name in ROW_FIELDS) + "},\n")
        out.write("};\n\n} // namespace DemoTrack\n")

    print(f"{TRACK_ROWS} rows, {bridged} depth rows bridged")


if __name__ == "__main__":
    main()
