#!/usr/bin/env python3
# Regenerates tests/celestial/horizons_fixture.h from the JPL Horizons API.
# Uses curl for HTTPS (system trust store).
# Usage: python3 -I tests/celestial/tools/fetch_horizons.py > tests/celestial/horizons_fixture.h
#
# Reference data (independent of Astronomy Engine):
#   - geocentric apparent RA/Dec of date (airless), CENTER 500@399, quantity 2
#   - local apparent sidereal time at each site, quantity 7
#   - topocentric airless apparent az/el of the Sun at each site, quantity 4

import subprocess
import urllib.parse

TIMES = [  # (label, Horizons time, unix UTC)
    ("2026-06-21 10:00", "2026-06-21 10:00", 1782036000),
    ("2026-12-21 10:00", "2026-12-21 10:00", 1797847200),
    ("2026-10-14 16:15", "2026-10-14 16:15", 1791994500),
    ("2026-07-15 07:10", "2026-07-15 07:10", 1784099400),  # watch demo epoch (DemoValues::DEMO_EPOCH_UTC)
]
SITES = [  # (label, lat, lon)
    ("Helsinki", 60.15, 24.95),
    ("Santiago", -33.90, -70.60),
    ("Demo", 60.0833, 24.8333),  # watch demo track start (DemoValues::START_LAT/LON_DEG)
]
BODIES = [("SUN", "10"), ("MOON", "301"), ("VENUS", "299"), ("MARS", "499"), ("JUPITER", "599"), ("SATURN", "699")]


def horizons(params):
    base = {
        "format": "text", "OBJ_DATA": "'NO'", "EPHEM_TYPE": "'OBSERVER'",
        "ANG_FORMAT": "'DEG'", "EXTRA_PREC": "'YES'", "CSV_FORMAT": "'YES'", "STEP_SIZE": "'1 m'",
    }
    base.update(params)
    url = "https://ssd.jpl.nasa.gov/api/horizons.api?" + urllib.parse.urlencode(base, safe="'@,")
    text = subprocess.run(["curl", "-sS", "--max-time", "60", url], check=True, capture_output=True, text=True).stdout
    rows = text.split("$$SOE")[1].split("$$EOE")[0].strip().splitlines()
    return [c.strip() for c in rows[0].split(",")]


def window(t):
    start = t
    stop = t[:-2] + "%02d" % (int(t[-2:]) + 1)
    return {"START_TIME": "'%s'" % start, "STOP_TIME": "'%s'" % stop}


print("#pragma once")
print("// Generated by tests/celestial/tools/fetch_horizons.py from JPL Horizons. Do not edit.")
print("struct HorizonsGeo  { const char* body; int time_idx; double ra_deg; double dec_deg; };")
print("struct HorizonsSite { int time_idx; double lat; double lon; double last_hours; double sun_az; double sun_el; };")
print("static const double HZ_TIMES_UNIX[] = { %s };" % ", ".join(str(t[2]) for t in TIMES))
print("static const HorizonsGeo HZ_GEO[] = {")
for ti, (label, t, _) in enumerate(TIMES):
    for name, cmd in BODIES:
        c = horizons({"COMMAND": "'%s'" % cmd, "CENTER": "'500@399'", "QUANTITIES": "'2'", **window(t)})
        print('    { "%s", %d, %s, %s },  // %s' % (name, ti, c[3], c[4], label))
print("};")
print("static const HorizonsSite HZ_SITES[] = {")
for ti, (label, t, _) in enumerate(TIMES):
    for sname, lat, lon in SITES:
        c = horizons({"COMMAND": "'10'", "CENTER": "'coord@399'", "COORD_TYPE": "'GEODETIC'",
                      "SITE_COORD": "'%s,%s,0'" % (lon, lat), "QUANTITIES": "'4,7'", **window(t)})
        print("    { %d, %s, %s, %s, %s, %s },  // %s %s" % (ti, lat, lon, c[5], c[3], c[4], sname, label))
print("};")
