#!/usr/bin/env python3
# Regenerates tests/celestial/simbad_fixture.h: SIMBAD J2000 positions looked up by the star's
# proper NAME (not by HIP number), so the test catches a name ↔ position mix-up in NavStars.cpp.
# Uses curl for HTTPS (system trust store).
# Usage: python3 -I tests/celestial/tools/fetch_simbad.py > tests/celestial/simbad_fixture.h

import csv
import io
import re
import subprocess

SIMBAD_ALIASES = {"Al Na'ir": "Alnair"}   # almanac name → SIMBAD NAME identifier

names = []
for line in open("NavStars.cpp"):
    m = re.match(r'\s*\{ "([^"]+)",', line)
    if m:
        names.append(m.group(1))

ids = ",".join("'NAME %s'" % SIMBAD_ALIASES.get(n, n).replace("'", "''") for n in names)
query = ("SELECT i.id, h.id AS hip, b.ra, b.dec FROM ident AS i JOIN basic AS b ON i.oidref = b.oid "
         "JOIN ident AS h ON h.oidref = b.oid WHERE i.id IN (%s) AND h.id LIKE 'HIP %%'" % ids)
out = subprocess.run(["curl", "-sS", "--max-time", "60", "-G", "https://simbad.cds.unistra.fr/simbad/sim-tap/sync",
                      "--data-urlencode", "request=doQuery", "--data-urlencode", "lang=adql",
                      "--data-urlencode", "format=csv", "--data-urlencode", "query=" + query],
                     check=True, capture_output=True, text=True).stdout
rows = {r["id"][5:]: r for r in csv.DictReader(io.StringIO(out))}

print("#pragma once")
print("// Generated by tests/celestial/tools/fetch_simbad.py from SIMBAD. Do not edit.")
print("struct SimbadStar { const char* name; unsigned hip; double ra_deg; double dec_deg; };")
print("static const SimbadStar SIMBAD_STARS[] = {")
for n in names:
    r = rows[SIMBAD_ALIASES.get(n, n)]
    print('    { "%s", %s, %s, %s },' % (n, r["hip"][4:], r["ra"], r["dec"]))
print("};")
